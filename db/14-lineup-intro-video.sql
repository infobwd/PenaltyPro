-- ---------------------------------------------------------------------
-- 14. คลิปแนะนำตัวสำหรับผังตัวนักกีฬา
--
-- ใช้กับหน้า /lineup ที่ขึ้นจอโปรเจกเตอร์ในสนามระหว่างรอเริ่มแข่ง
-- ให้ช่วงแนะนำทีมมีคลิปสั้นเล่นเป็นพื้นหลัง และการ์ดนักกีฬารายคนกดดูคลิปได้
--
-- ทำไมแยกจาก matches.highlight_url:
--   highlight_url = คลิปของ "นัด" ลงหลังแข่งจบ
--   intro_video_url = คลิปของ "คน/ทีม" เตรียมไว้ก่อนเริ่มรายการ ใช้ซ้ำได้ทุกนัด
--
-- เก็บ URL ดิบตามที่วางมา (youtu.be / watch?v= / shorts / embed ก็ได้)
-- ฝั่งเว็บแปลงเป็น embed เอง ดู services/youtube.ts — จะได้ไม่ต้องบังคับให้
-- เจ้าภาพจำรูปแบบ ซึ่งเป็นจุดที่คนกรอกผิดแล้วคลิปไม่ขึ้นโดยไม่มีคำอธิบาย
--
-- ⚠️ ต้องรันไฟล์นี้ ไม่งั้นแท็บ "ออกอากาศ" ในหน้าแก้ไขทีมจะกรอกได้แต่ไม่บันทึก
--
-- ค่าว่าง = ไม่มีคลิป ผังตัวนักกีฬาจะแสดงแบบเดิมทุกอย่าง
-- ---------------------------------------------------------------------

ALTER TABLE players
  ADD COLUMN intro_video_url VARCHAR(500) NOT NULL DEFAULT ''
    COMMENT 'คลิปแนะนำนักกีฬารายคน (YouTube) — ว่างคือไม่มี'
    AFTER photo_url;

ALTER TABLE teams
  ADD COLUMN intro_video_url VARCHAR(500) NOT NULL DEFAULT ''
    COMMENT 'คลิปแนะนำทีม (YouTube) — เล่นเป็นพื้นหลังตอนเปิดตัวทีม'
    AFTER logo_url,
  ADD COLUMN hype_text VARCHAR(200) NOT NULL DEFAULT ''
    COMMENT 'คำโปรยประจำทีม เช่น "แชมป์เก่า 2 สมัย" — ขึ้นใต้ชื่อทีมบนจอ'
    AFTER intro_video_url;
