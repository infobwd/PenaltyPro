-- ประวัติจะไม่ถูกเขียนโดยไม่มีใครรู้ — ตรวจพบตอนทดสอบ db/28 กับฐานข้อมูลจริง
--
-- คนที่ต้องตามย้อนหลังได้มากที่สุดคือกรรมการกับคนที่ถือรหัสเริ่มแข่ง
-- เพราะทั้งคู่คือคนที่เขียนผลการแข่งขันที่ออกอากาศสด
-- ---------------------------------------------------------------------

