--
-- ⚠️ นี่คือบั๊กที่มีอยู่ก่อนแล้ว ไม่ใช่ของใหม่จากรหัสเริ่มแข่ง
-- db/13 เพิ่มบทบาท 'referee' ให้ users.role แต่ไม่ได้เพิ่มให้ ENUM ตัวนี้ด้วย
