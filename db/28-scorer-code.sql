-- ---------------------------------------------------------------------
-- 28. รหัสเริ่มแข่ง — บันทึกผลได้โดยไม่ต้องมีบัญชี
--
-- ── ปัญหาที่แก้ ──────────────────────────────────────────────────────
-- หน้าจอมีช่อง "กรุณากรอกรหัสเริ่มแข่ง" อยู่แล้ว แต่มันเทียบรหัสในเบราว์เซอร์
-- แล้วเปิดหน้าจอบันทึกผลให้เฉย ๆ ส่วนตอนกดบันทึกจริง server ตอบ 401
-- เพราะทุก action ของการบันทึกผลต้อง Auth::requireLogin()
-- ผลคือกรรมการที่ไม่มีบัญชีกรอกรหัสถูกก็บันทึกอะไรไม่ได้อยู่ดี
-- (และรหัสที่เทียบคือค่าคงที่ '1234' เพราะ adminPin ไม่ถูกส่งให้คนทั่วไป)
--
-- ── ทำไมเป็นรหัสของ "แต่ละรายการ" ไม่ใช่รหัสเดียวทั้งระบบ ────────────
-- รหัสนี้ต้องบอกต่อกันปากเปล่าหน้าสนาม วันงานมีคนรู้หลายสิบคน
-- ถือว่าหลุดตั้งแต่วันแรก — สิ่งที่ควบคุมได้คือ "หลุดแล้วเสียหายแค่ไหน"
-- ผูกกับรายการเดียว = คนที่รู้รหัสงานอำเภอทุ่งเสลี่ยม แตะผลของงานอื่นไม่ได้เลย
-- ถ้าใช้รหัสเดียวทั้งระบบ รหัสที่หลุดจากงานเดียวจะเปิดทุกงานตลอดไป
--
-- ── ทำไมเก็บเป็น hash ──────────────────────────────────────────────
-- เหมือนรหัสโรงเรียน (schools.access_code_hash) — ฐานข้อมูลหลุดเมื่อไหร่
-- รหัสที่ยังใช้งานอยู่ต้องไม่ติดไปด้วย และไม่มีใครแอบดูรหัสจาก phpMyAdmin ได้
-- ผู้ดูแลดูรหัสย้อนหลังไม่ได้ ต้องตั้งใหม่อย่างเดียว ซึ่งถูกแล้ว
--
-- ⚠️ ต้องรัน db/01 ถึง db/27 ก่อนไฟล์นี้
-- ลบตารางนี้กับคอลัมน์ทั้งสามทิ้ง ระบบเดิมยังทำงานครบเหมือนไม่เคยมี
-- (การบันทึกผลจะกลับไปเป็น "ต้องเข้าระบบเท่านั้น")
-- ---------------------------------------------------------------------

SET NAMES utf8mb4;

ALTER TABLE tournaments
  ADD COLUMN scorer_code_hash VARCHAR(255) NULL
      COMMENT 'รหัสเริ่มแข่ง เก็บเป็น hash — NULL = ปิด ต้องเข้าระบบเท่านั้น',
  ADD COLUMN scorer_code_set_at DATETIME NULL
      COMMENT 'ตั้งล่าสุดเมื่อไหร่ — ไว้ให้ผู้ดูแลรู้ว่ารหัสเก่าแค่ไหน',
  ADD COLUMN scorer_code_set_by VARCHAR(40) NULL
      COMMENT 'ใครเป็นคนตั้ง — ไว้ตามย้อนหลัง';

-- ค่าเริ่มต้นเป็น NULL ทุกแถวโดยตั้งใจ
-- ของเดิมไม่เคยมีรหัสที่ใช้ได้จริง การเปิดให้ทุกรายการทันทีจึงเป็นการ
-- เพิ่มทางเข้าใหม่ให้ระบบที่กำลังใช้งานอยู่โดยที่ไม่มีใครสั่ง
-- ผู้ดูแลต้องเข้าไปตั้งรหัสของรายการนั้นเองก่อน ถึงจะเปิดทาง

CREATE TABLE scorer_sessions (
  token_hash    CHAR(64)     NOT NULL COMMENT 'sha256 ของ token ที่ส่งให้เครื่องกรรมการ',
  tournament_id VARCHAR(40)  NOT NULL,
  label         VARCHAR(80)  NOT NULL DEFAULT ''
                COMMENT 'ชื่อที่กรรมการกรอกไว้ — ไว้ดูว่าใครบันทึกจากเครื่องไหน',
  issued_at     DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at    DATETIME     NOT NULL,
  revoked_at    DATETIME     NULL,
  last_seen_at  DATETIME     NULL,
  ip_hash       CHAR(64)     NOT NULL DEFAULT '' COMMENT 'ค่าแฮช ไม่ใช่ IP',
  user_agent    VARCHAR(255) NOT NULL DEFAULT '',
  PRIMARY KEY (token_hash),

  -- ตั้งรหัสใหม่ = ลบทุกแถวของรายการนั้น เพื่อเตะเครื่องที่ถือรหัสเก่าออกทันที
  KEY idx_scorer_tournament (tournament_id, expires_at),

  CONSTRAINT fk_scorer_tournament FOREIGN KEY (tournament_id)
    REFERENCES tournaments (tournament_id) ON UPDATE CASCADE ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='session ของกรรมการที่เข้าด้วยรหัสเริ่มแข่ง — บันทึกผลได้รายการเดียว';

