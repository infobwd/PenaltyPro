-- ---------------------------------------------------------------------
-- 09. ผูก session โรงเรียนกับผู้ใช้ที่เข้าระบบอยู่
--
-- ที่มา: ครูบ่นว่า "เพิ่งเข้าระบบไม่นานก็ขึ้นเซสชันหมดอายุ"
--
-- เดิม token หนึ่งใบเป็นได้อย่างเดียว — ถ้าเป็น team_session ก็ไม่มี user
-- พอครูเข้าสู่ระบบด้วย LINE แล้วกดเข้าหน้าโรงเรียน token จะถูกสลับเป็นของทีม
-- คำขออะไรก็ตามที่ต้อง requireLogin() (เช่น ดึงจำนวนแจ้งเตือน) จึงตอบ 401
-- แล้วฝั่งเว็บก็ล้าง session ทิ้งพร้อมข้อความ "เซสชันหมดอายุ"
--
-- แก้ที่ต้นเหตุ: จำไว้ว่า session ทีมนี้ออกให้ใคร เวลา boot จะได้โหลด
-- ทั้งสิทธิ์โรงเรียนและตัวผู้ใช้ขึ้นมาพร้อมกัน
--
-- NULL = เข้าด้วยรหัสโรงเรียน 8 ตัวล้วน ๆ ไม่ได้ผูกกับบัญชีใคร (ยังใช้ได้เหมือนเดิม)
-- ON DELETE SET NULL = ลบบัญชีผู้ใช้แล้ว session ทีมไม่ต้องหายตาม
-- ---------------------------------------------------------------------

ALTER TABLE team_sessions
  ADD COLUMN user_id VARCHAR(40) NULL DEFAULT NULL
    COMMENT 'ผู้ใช้ที่เข้าหน้าโรงเรียนนี้ — NULL คือเข้าด้วยรหัสโรงเรียนล้วน'
    AFTER tournament_id,
  ADD KEY idx_tsessions_user (user_id),
  ADD CONSTRAINT fk_tsessions_user FOREIGN KEY (user_id)
    REFERENCES users (user_id) ON UPDATE CASCADE ON DELETE SET NULL;
