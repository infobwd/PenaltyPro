--  เก็บรหัสโรงเรียนแบบถอดกลับได้ เพื่อให้ผู้ดูแลเปิดดูได้ภายหลัง
--  (รันหลัง 01-schema.sql และ 03-tournament-admins.sql)
--
--  ═══ ข้อแลกเปลี่ยนที่ต้องรู้ ═══
--  เดิมเก็บเฉพาะ hash (bcrypt) ซึ่งถอดกลับไม่ได้ แปลว่าถึงฐานข้อมูลหลุด
--  รหัสก็ยังใช้ไม่ได้ แต่ผลข้างเคียงคือ "ลืมรหัส" ต้องออกใหม่เสมอ ซึ่งทำให้
--  รหัสที่แจกไปแล้วตายทันที และครูที่ยังไม่ได้ใช้ก็เข้าไม่ได้ตามไปด้วย
--
--  ตารางนี้เพิ่มสำเนาที่ "เข้ารหัส" ไว้ด้วย (AES-256-GCM ด้วย app_secret)
--  ผู้ดูแลจึงเปิดดูรหัสเดิมเพื่อบอกครูทางโทรศัพท์ได้ โดยไม่ต้องออกรหัสใหม่
--
--  สิ่งที่อ่อนลง: ใครที่ได้ทั้งฐานข้อมูล *และ* ค่า app_secret ใน config.php
--  จะถอดรหัสได้ทั้งหมด — ต่างจากเดิมที่ได้ฐานข้อมูลไปก็ทำอะไรไม่ได้
--  จึงต้องกันไฟล์ config.php ให้ดี (อยู่ใน .gitignore แล้ว) และเปลี่ยน
--  app_secret ทันทีถ้าสงสัยว่าหลุด
--
--  การตรวจรหัสตอนล็อกอินยังใช้ hash เหมือนเดิม ไม่ได้ใช้ค่าที่เข้ารหัสนี้
-- =====================================================================

SET NAMES utf8mb4;

ALTER TABLE schools
  ADD COLUMN access_code_enc VARBINARY(255) NULL
      COMMENT 'รหัสเดิมที่เข้ารหัสไว้ให้ผู้ดูแลเปิดดูได้ — ไม่ใช้ตอนตรวจล็อกอิน'
      AFTER access_code_hash,
  ADD COLUMN access_code_revealed_at DATETIME NULL
      COMMENT 'เปิดดูล่าสุดเมื่อไหร่ (ทุกครั้งบันทึกลง audit_log ด้วย)'
      AFTER access_code_used_at;
