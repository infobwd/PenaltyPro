-- แยก "โรงเรียนที่ผู้ใช้เลือกเอง" ออกจาก "โรงเรียนที่ผู้ดูแลรับรอง"
--
-- ที่ต้องมี: users.school_id ถูกตั้งได้ 2 ทาง
--   1. ผู้ใช้เลือกเองตอนเข้าครั้งแรก (setMySchool) — เป็นแค่คำบอกเล่า ใครก็เลือกอะไรก็ได้
--   2. ผู้ดูแลกำหนดให้จากหน้าจัดการผู้ใช้ — ผ่านการตรวจสอบตัวตนมาแล้ว
--
-- ถ้าให้ทั้งสองแบบเข้าไปแก้ทีมของโรงเรียนได้เหมือนกัน จะกลายเป็นช่องโหว่ทันที:
-- ใครก็ตามที่เข้าด้วย LINE แล้วเลือกว่า "ฉันอยู่โรงเรียนบ้านวังด้ง" จะแก้รายชื่อ
-- นักกีฬาของโรงเรียนนั้นได้เลย ทั้งที่ไม่ได้เกี่ยวข้องอะไรด้วย
--
-- คอลัมน์นี้จึงเป็นตัวชี้ว่า "ผูกโดยผู้ดูแล" เท่านั้นที่ข้ามการกรอกรหัส 8 ตัวได้

SET NAMES utf8mb4;

ALTER TABLE users
  ADD COLUMN school_verified TINYINT(1) NOT NULL DEFAULT 0
      COMMENT '1 = ผู้ดูแลเป็นคนผูกให้ (เข้าจัดการทีมได้โดยไม่ต้องกรอกรหัส), 0 = ผู้ใช้เลือกเอง'
      AFTER school_set_at,
  ADD COLUMN school_verified_by VARCHAR(40) NULL
      COMMENT 'ผู้ดูแลที่รับรอง — ไว้ตามย้อนหลังว่าใครให้สิทธิ์'
      AFTER school_verified;

-- ผู้ใช้ที่มีอยู่ก่อนหน้านี้ทั้งหมดถือว่า "เลือกเอง" ไว้ก่อน (ค่าเริ่มต้น 0)
-- ผู้ดูแลต้องเข้าไปกดรับรองรายคน — ปลอดภัยกว่าการเปิดสิทธิ์ให้ทุกคนย้อนหลัง
