-- 12. วิดีโอไฮไลต์ของแต่ละคู่
--
-- แยกจาก livestream_url เพราะเป็นคนละอย่างและมีพร้อมกันได้:
--   livestream_url = ลิงก์ถ่ายทอดสดตอนกำลังแข่ง
--   highlight_url  = คลิปไฮไลต์/ย้อนหลังที่ตัดมาแล้ว ลงทีหลัง
--
-- เดิมหน้า Replay Gallery ใน live_wall ใช้ livestream_url ของคู่ที่จบแล้วแทน
-- ซึ่งพอเจ้าภาพลงคลิปไฮไลต์จริงก็ต้องเขียนทับลิงก์ถ่ายทอดสดทิ้ง
-- ลิงก์เดิมที่เคยแชร์ออกไปแล้วจึงพากลับมาดูของเดิมไม่ได้
--
-- เก็บ URL ดิบตามที่วางมา (youtu.be / watch?v= / embed ก็ได้)
-- ฝั่งเว็บแปลงเป็น embed เอง จะได้ไม่ต้องบังคับให้ผู้ใช้จำรูปแบบ
-- ---------------------------------------------------------------------

ALTER TABLE matches
  ADD COLUMN highlight_url VARCHAR(500) NOT NULL DEFAULT ''
    COMMENT 'ลิงก์คลิปไฮไลต์ (YouTube) — ว่างคือยังไม่มี'
    AFTER livestream_cover,
  ADD COLUMN highlight_title VARCHAR(200) NOT NULL DEFAULT ''
    COMMENT 'ชื่อคลิป — ว่างคือใช้ชื่อคู่แข่งขันแทน'
    AFTER highlight_url;
