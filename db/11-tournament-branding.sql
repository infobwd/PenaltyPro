-- ---------------------------------------------------------------------
-- 11. โลโก้และประกาศประจำรายการแข่งขัน
--
-- ย้ายมาจากแท็บ "ตั้งค่า" ระดับระบบ เพราะทุกปีเปลี่ยนโลโก้และประกาศใหม่
-- ถ้าเก็บไว้ระดับระบบ พอเปิดดูรายการเก่าจะเห็นโลโก้ของปีปัจจุบันติดอยู่
-- ซึ่งไม่ตรงกับความจริง
--
-- ⚠️ ต้องรันไฟล์นี้ ไม่งั้นช่อง "โลโก้รายการ" กับ "ประกาศวิ่งหน้าแรก"
-- ในโมดัลตั้งค่ารายการแข่งขันจะกรอกได้แต่ไม่บันทึกอะไรเลย
--
-- ค่าว่าง = ใช้ของกลางจากแท็บตั้งค่าแทน (ดู effectiveSettings ใน App.tsx)
-- ---------------------------------------------------------------------

ALTER TABLE tournaments
  ADD COLUMN competition_logo VARCHAR(500) NOT NULL DEFAULT ''
    COMMENT 'โลโก้ประจำรายการ — ว่างคือใช้โลโก้กลาง'
    AFTER name,
  ADD COLUMN announcement TEXT NULL
    COMMENT 'ประกาศวิ่งหน้าแรก คั่นหลายข้อความด้วย | — ว่างคือใช้ของกลาง'
    AFTER competition_logo;
