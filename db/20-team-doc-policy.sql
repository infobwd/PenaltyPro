-- ---------------------------------------------------------------------
-- 20. นโยบายเอกสารรับรองของทีม (หน้า /school)
--
-- เดิมช่อง "เอกสารรับรอง" ขึ้นให้ทุกโรงเรียนเสมอและไม่บังคับ ทั้งที่แต่ละงาน
-- ต้องการไม่เหมือนกัน — บางงานไม่ขอเอกสารเลย บางงานต้องมีหนังสือรับรอง
-- จากผู้อำนวยการก่อนถึงจะรับสมัคร ครูจึงต้องไปถามในไลน์กลุ่มทุกปีว่าต้องส่งไหม
--
-- doc_mode:
--   Off      ไม่รับเอกสาร — ซ่อนช่องอัปโหลดไปเลย
--   Optional รับแต่ไม่บังคับ (พฤติกรรมเดิม จึงเป็นค่าเริ่มต้น)
--   Required ต้องแนบก่อนกดยืนยันส่งรายชื่อ
--
-- doc_template_url: ไฟล์ตัวอย่าง/แบบฟอร์มให้โรงเรียนดาวน์โหลดไปกรอก
-- ว่าง = ไม่มีไฟล์ตัวอย่าง ปุ่มดาวน์โหลดจะไม่ขึ้น
--
-- ⚠️ ต้องรันไฟล์นี้ ไม่งั้นการตั้งค่าในหน้าจัดการรายการจะกรอกได้แต่ไม่บันทึก
--
-- ค่าเริ่มต้นเป็น Optional ทุกรายการ พฤติกรรมจึงไม่เปลี่ยนจนกว่าเจ้าภาพจะตั้งเอง
-- ---------------------------------------------------------------------

ALTER TABLE tournaments
  ADD COLUMN doc_mode ENUM('Off','Optional','Required') NOT NULL DEFAULT 'Optional'
    COMMENT 'นโยบายเอกสารรับรองของทีมในหน้า /school'
    AFTER max_subs,
  ADD COLUMN doc_template_url VARCHAR(500) NOT NULL DEFAULT ''
    COMMENT 'ไฟล์ตัวอย่าง/แบบฟอร์มให้โรงเรียนดาวน์โหลด — ว่างคือไม่มี'
    AFTER doc_mode;
