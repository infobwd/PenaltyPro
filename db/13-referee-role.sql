-- referee ทำได้อย่างเดียวคือบันทึกผลของรายการที่ถูกมอบหมาย
-- (ผ่านตาราง tournament_managers เหมือนผู้ดูแลรายการ แต่ไม่ได้สิทธิ์ staff)
--
-- ⚠️ ต้องมี username + รหัสผ่าน เหมือน admin/staff เพราะบัญชี LINE ล้วน
-- ยืนยันตัวตนไม่พอสำหรับคนที่เขียนผลการแข่งขันได้
-- (chk_staff_has_password เดิมครอบให้แล้ว เพราะเงื่อนไขคือ role = 'user'
--  เท่านั้นที่ไม่ต้องมีรหัสผ่าน — referee จึงถูกบังคับอัตโนมัติ)
