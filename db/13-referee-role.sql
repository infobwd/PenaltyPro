-- ที่มา: การบันทึกผลต้องผ่าน Perm::requireTournamentManager ซึ่งเดิมต้องเป็น
-- admin หรือ staff เท่านั้น ทำให้ต้องยกกรรมการขึ้นเป็น staff — แล้วกรรมการ
-- ก็เห็นรายชื่อผู้ใช้ทั้งระบบ เงินบริจาค และหลังบ้านทั้งหมดไปด้วย
-- ซึ่งเกินความจำเป็นและเป็นความเสี่ยงที่ไม่ควรรับในงานแข่งกีฬาโรงเรียน
