-- ---------------------------------------------------------------------
-- 22. เปิดหน้าเกียรติบัตรให้ผู้ใช้ทั่วไป + ใบอนุโมทนาผู้สนับสนุน
--
-- ── cert_public ─────────────────────────────────────────────────────
-- ค่าเริ่มต้นเป็นปิด เพราะระหว่างที่เจ้าภาพยังตั้งข้อความและลายเซ็นไม่เสร็จ
-- ใบที่ผู้ปกครองโหลดไปจะเป็นใบเปล่าที่ไม่มีชื่อผู้ลงนาม เรียกคืนไม่ได้แล้ว
-- เจ้าภาพจึงต้องกดเปิดเองเมื่อพร้อมแจก
--
-- ── Sponsor ในตารางเลขที่ ───────────────────────────────────────────
-- ใบอนุโมทนาของผู้สนับสนุนเดินเลขคนละชุดกับนักกีฬา/กรรมการ และต้องเป็นเลข
-- ที่ "ล็อกกับผู้สนับสนุนรายนั้น" เหมือนกัน จึงใช้กลไกเดียวกันทั้งหมด
-- (ตัวเลขที่จัดรูปแล้วยังถูกเก็บซ้ำที่ sponsors.acknowledgement_no
--  เพื่อให้ใบที่เคยออกไปแล้วก่อนมีไฟล์นี้ยังพิมพ์ได้เลขเดิม)
--
-- ⚠️ ต้องรัน db/21-certificates.sql ก่อนไฟล์นี้
-- ---------------------------------------------------------------------

ALTER TABLE tournaments
  ADD COLUMN cert_public TINYINT(1) NOT NULL DEFAULT 0
    COMMENT '1 = ผู้ใช้ทั่วไปเข้าหน้าเกียรติบัตรและโหลดใบของตัวเองได้'
    AFTER cert_no_digits,
  ADD COLUMN cert_no_sponsor VARCHAR(100) NOT NULL DEFAULT ''
    COMMENT 'รูปแบบเลขที่ใบอนุโมทนา ใช้ {n} เป็นช่องเลข เช่น "อศ. {n}/2569"'
    AFTER cert_public;

ALTER TABLE certificate_issues
  MODIFY COLUMN role ENUM('Player','Coach','Referee','Sponsor') NOT NULL;
